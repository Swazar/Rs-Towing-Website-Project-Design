import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import { effectiveWorkspace, workspaceDefaults, resolveWorkspace, validateWorkspace, availablePanels, workspacePanels } from '../public/assets/workspace-config.js';
import { WorkspaceLayout } from '../public/assets/workspace-layout.js';
import { WorkspaceCustomizer } from '../public/assets/workspace-customizer.js';
import { validateProfile } from '../netlify/lib/profile.mjs';

test('versioned workspace preferences recover old data and reject malformed writes', () => {
  assert.deepEqual(resolveWorkspace(null), workspaceDefaults());
  const migrated = resolveWorkspace({ version: 1, preset: 'compact', panelOrder: ['calendar'], hiddenPanels: ['removed-panel', 'map'], fontSize: 900 });
  assert.equal(migrated.panelOrder[0], 'calendar');
  assert.equal(migrated.panelOrder.length, workspacePanels.length, 'new registry panels join older saved layouts');
  assert.equal(new Set(migrated.panelOrder).size, workspacePanels.length);
  assert.deepEqual(migrated.hiddenPanels, ['map']);
  assert.equal(migrated.fontSize, 100);
  assert.equal(migrated.layout, 'equal');
  assert.deepEqual(resolveWorkspace({ version: 99 }), workspaceDefaults());
  for (const invalid of [null, [], { ...workspaceDefaults(), version: 2 }, { ...workspaceDefaults(), fontSize: 0 }, { ...workspaceDefaults(), hiddenPanels: ['admin'] }, { ...workspaceDefaults(), panelOrder: ['map', 'map'] }]) assert.throws(() => validateWorkspace(invalid), /workspace/);
  const before = { displayName: 'Alex', avatar: '', workspace: { ...workspaceDefaults(), hiddenPanels: ['map'] } };
  const saved = validateProfile({ displayName: 'Alex', phone: '123' }, before);
  assert.deepEqual(saved.workspace, before.workspace, 'older profile clients do not reset layout preferences');
});

test('presets own desktop layout and typography while mobile keeps one fixed presentation', async () => {
  const desktop = { ...workspaceDefaults(), theme: 'ocean', preset: 'spacious', layout: 'equal', fontSize: 125, panelOrder: [...workspaceDefaults().panelOrder].reverse(), hiddenPanels: ['map'] };
  const mobile = effectiveWorkspace(desktop, true);
  assert.equal(mobile.layout, 'single'); assert.equal(mobile.preset, 'balanced');
  assert.deepEqual(mobile.panelOrder, workspaceDefaults().panelOrder);
  assert.equal(mobile.theme, 'ocean'); assert.equal(mobile.fontSize, 100);
  assert.deepEqual(mobile.hiddenPanels, ['map']);
  assert.deepEqual(effectiveWorkspace(desktop, false), { ...desktop, layout: 'single', fontSize: 110 }, 'legacy fine-tuning cannot conflict with a preset');
  assert.equal(desktop.fontSize, 125, 'deriving a presentation does not mutate saved data');
  assert.throws(() => validateWorkspace({ ...desktop, theme: 'unrecognized' }), /workspace/);
  const legacy = { ...workspaceDefaults() }; delete legacy.theme;
  assert.equal(validateWorkspace(legacy).theme, 'rs-red', 'existing accounts retain the original theme');
  const html = await readFile(new URL('../public/admin/index.html', import.meta.url), 'utf8');
  const dom = new JSDOM(html), document = dom.window.document;
  let isMobile = false, resize;
  dom.window.matchMedia = () => ({ get matches() { return isMobile; }, addEventListener(type, callback) { resize = callback; } });
  const layout = new WorkspaceLayout(document, () => {}); layout.apply(desktop, ['jobs', 'content', 'activity']);
  isMobile = true; resize();
  assert.equal(layout.grid.dataset.layout, 'single');
  assert.equal(document.body.dataset.workspaceDensity, 'balanced');
  assert.deepEqual([...layout.grid.children].map(el => el.dataset.workspacePanel), workspaceDefaults().panelOrder);
  isMobile = false; resize();
  assert.equal(layout.grid.dataset.layout, 'single');
  assert.equal(document.body.dataset.workspaceDensity, 'spacious');
  assert.equal(document.body.dataset.workspaceTheme, 'ocean');
  assert.deepEqual([...layout.grid.children].map(el => el.dataset.workspacePanel), desktop.panelOrder);
  dom.window.close();
});

test('themes and panel help keep native controls without redundant fine-tuning options', () => {
  const dom = new JSDOM('<div id="customizer"></div><div id="workspace-themes"></div>'), document = dom.window.document;
  dom.window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  dom.window.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new dom.window.Event('close')); };
  const changes = [], customizer = new WorkspaceCustomizer(document.querySelector('#customizer'), value => changes.push(value));
  customizer.load(workspaceDefaults(), ['jobs']);
  assert.equal(document.querySelectorAll('[name="workspace-theme"]').length, 4);
  assert.equal(document.querySelectorAll('[name="workspace-theme"]').length, 4, 'theme choices use styled native radios');
  assert.equal(document.querySelector('[name="workspace-font-size"]'), null);
  assert.equal(document.querySelector('[name="workspace-layout"]'), null);
  document.querySelector('[name="workspace-theme"][value="ocean"]').click();
  assert.equal(changes.at(-1).theme, 'ocean');
  const help = document.querySelector('.workspace-help-trigger'); help.focus(); help.click();
  const dialog = document.querySelector('#workspace-panel-help'); assert.equal(dialog.open, true);
  assert.match(dialog.textContent, /Hiding a panel keeps its data/);
  dialog.querySelector('button').click(); assert.equal(dialog.open, false); assert.equal(document.activeElement, help);
  assert.ok(document.querySelector('.workspace-panel-thumbnail[aria-hidden="true"]'));
  document.querySelector('#workspace-reset').click(); assert.equal(customizer.value.theme, 'rs-red');
  dom.window.close();
});

test('workspace reorders actual DOM, keeps role restrictions, and recovers from hiding every panel', async () => {
  const html = await readFile(new URL('../public/admin/index.html', import.meta.url), 'utf8');
  const dom = new JSDOM(html), document = dom.window.document;
  let customized = 0;
  const layout = new WorkspaceLayout(document, () => customized++);
  const order = [...workspaceDefaults().panelOrder].reverse();
  layout.apply({ ...workspaceDefaults(), preset: 'spacious', panelOrder: order, hiddenPanels: ['map'] }, ['jobs']);
  assert.deepEqual([...document.querySelector('.overview-grid').children].map(element => element.dataset.workspacePanel), order);
  assert.equal(document.querySelector('[data-workspace-panel="map"]').hidden, true);
  assert.equal(document.querySelector('[data-workspace-panel="quickEdits"]').hidden, true);
  assert.equal(document.querySelector('[data-workspace-panel="activity"]').hidden, true);
  assert.equal(document.querySelector('.overview-column'), null);
  assert.equal(document.documentElement.style.getPropertyValue('--workspace-font-scale'), '1.1');
  layout.apply({ ...workspaceDefaults(), hiddenPanels: availablePanels(['jobs']).map(panel => panel.id) }, ['jobs']);
  assert.equal(layout.grid.hidden, true);
  assert.equal(layout.empty.hidden, false);
  layout.empty.querySelector('button').click(); assert.equal(customized, 1);
  layout.apply(workspaceDefaults(), ['jobs']);
  assert.equal(layout.grid.hidden, false);
  assert.equal(layout.empty.hidden, true);
  assert.equal(document.querySelector('[data-workspace-panel="quickEdits"]').hidden, true, 'restoring defaults cannot grant owner access');
  layout.clear(); assert.equal(document.documentElement.classList.contains('workspace-customized'), false, 'login does not inherit the admin font scale');
  dom.window.close();
});

test('preset and panel controls support keyboard focus, per-user loads, and restore defaults', () => {
  const dom = new JSDOM('<div id="customizer"></div>'), document = dom.window.document;
  const changes = [];
  const customizer = new WorkspaceCustomizer(document.querySelector('#customizer'), value => changes.push(value));
  customizer.load(workspaceDefaults(), ['jobs', 'content', 'activity']);
  document.querySelector('input[value="spacious"]').click();
  assert.equal(changes.at(-1).layout, 'single');
  assert.equal(changes.at(-1).fontSize, 110);
  document.querySelector('[data-panel="map"]').click();
  assert.ok(changes.at(-1).hiddenPanels.includes('map'));
  const move = (id, rank) => { const select = document.querySelector('[data-position="' + id + '"]'); select.value = String(rank); select.dispatchEvent(new dom.window.Event('change')); };
  move('map', 0);
  assert.equal(customizer.value.panelOrder[0], 'map');
  assert.equal(customizer.value.panelOrder[1], 'summary', 'intervening panels shift rather than swapping');
  assert.equal(document.activeElement.getAttribute('aria-label'), 'Position of Job locations', 'focus follows the moved panel');
  move('map', 6);
  assert.equal(customizer.value.panelOrder[6], 'map');
  assert.equal(new Set(customizer.value.panelOrder).size, 7);
  assert.match(customizer.status.textContent, /position 7 of 7.*Save/);
  document.querySelector('#workspace-reset').click();
  assert.deepEqual(customizer.value, workspaceDefaults());
  customizer.load({ ...workspaceDefaults(), hiddenPanels: ['calendar'] }, ['jobs']);
  assert.equal(document.querySelector('[data-panel="calendar"]').checked, false);
  assert.equal(document.querySelector('[data-panel="quickEdits"]'), null, 'staff controls omit owner-only panels');
  assert.equal(document.querySelector('[data-position="quickEdits"]'), null);
  move('map', 0);
  assert.equal(customizer.value.panelOrder[0], 'map');
  assert.ok(customizer.value.panelOrder.includes('quickEdits'), 'reordering preserves unavailable panel entries');
  customizer.load(workspaceDefaults(), ['jobs']);
  assert.equal(document.querySelector('[data-panel="calendar"]').checked, true, 'switching account data never carries another admin’s choices');
  dom.window.close();
});
