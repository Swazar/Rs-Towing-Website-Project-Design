import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';
import { JSDOM } from 'jsdom';
import { WorkspaceNotice } from '../public/assets/admin-notice.js';

test('confirmations pause while being read; errors persist and dismissing restores focus', async () => {
  const html = await readFile(new URL('../public/admin/index.html', import.meta.url), 'utf8');
  const dom = new JSDOM(html, { pretendToBeVisual: true });
  const { window } = dom, document = window.document;
  document.querySelector('#owner-workspace').hidden = false;
  const scheduled = new Map(); let clock = 0, sequence = 0;
  window.setTimeout = (callback, delay) => { const id = ++sequence; scheduled.set(id, { callback, delay }); return id; };
  window.clearTimeout = id => scheduled.delete(id);
  Object.defineProperty(window.performance, 'now', { value: () => clock });
  const root = document.querySelector('#owner-notice'), notice = new WorkspaceNotice(root);
  const trigger = document.querySelector('#calendar-today'); trigger.focus();
  notice.show('Reminder saved', { detail: 'Your reminder is on the calendar.' });
  assert.equal(root.hidden, false);
  assert.equal(document.activeElement, trigger, 'A confirmation must not steal keyboard focus.');
  assert.equal(document.querySelector('#owner-message').getAttribute('role'), 'status');
  assert.equal([...scheduled.values()][0].delay, 8000);
  clock = 3000; root.dispatchEvent(new window.Event('mouseenter'));
  assert.equal(scheduled.size, 0);
  root.dispatchEvent(new window.Event('mouseleave'));
  assert.equal([...scheduled.values()][0].delay, 5000, 'Hover pauses rather than resets the remaining reading time.');
  const dismiss = document.querySelector('#owner-message-dismiss'); dismiss.focus();
  assert.equal(scheduled.size, 0, 'A notification cannot disappear while its controls have focus.');
  notice.show('The reminder could not be saved. Try again.', { tone: 'error' });
  assert.equal(scheduled.size, 0, 'Errors stay visible until dismissed.');
  assert.equal(document.querySelector('#owner-message').getAttribute('role'), 'alert');
  assert.match(document.querySelector('#owner-message-detail').textContent, /could not be saved/);
  dismiss.click();
  assert.equal(root.hidden, true);
  assert.equal(document.activeElement, trigger);
  notice.show('Enquiries refreshed.');
  assert.equal(scheduled.size, 1);
  [...scheduled.values()][0].callback();
  assert.equal(root.hidden, true);
  dom.window.close();
});
